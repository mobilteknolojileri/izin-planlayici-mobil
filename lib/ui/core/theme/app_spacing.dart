/// Spacing scale in logical pixels, on an 8 pt grid with a 4 pt half step.
abstract final class AppSpacing {
  /// 4, between an icon and its text.
  static const double xs = 4;

  /// 8, between related items.
  static const double sm = 8;

  /// 12, inside compact rows.
  static const double smd = 12;

  /// 16, screen edges and card padding.
  static const double md = 16;

  /// 20, inside the hero card.
  static const double mdl = 20;

  /// 24, between sections.
  static const double lg = 24;

  /// 32, around large illustrations.
  static const double xl = 32;

  /// 48, minimum touch target and large gaps.
  static const double xxl = 48;
}
